public class EvenOdd {
    public static void main(String[] args) {
        System.out.println("=== Проверка чётности ===");
        int num = 7;
        if (num % 2 == 0) {
            System.out.println(num + " - чётное число");
        } else {
            System.out.println(num + " - нечётное число");
        }
    }
}
